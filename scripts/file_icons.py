SATURATION = 0.72  # Quiet: keep 72% of each colour's saturation.
HEX = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")


def mute(match: re.Match[str]) -> str:
    raw = match.group(1)
    if len(raw) == 3:
        raw = "".join(c * 2 for c in raw)
    r, g, b = (int(raw[i : i + 2], 16) / 255 for i in (0, 2, 4))
    h, lightness, s = colorsys.rgb_to_hls(r, g, b)
    r, g, b = colorsys.hls_to_rgb(h, lightness, s * SATURATION)
    return "#" + "".join(f"{round(v * 255):02x}" for v in (r, g, b))


def svg(icons: Path, name: str) -> str:
    text = (icons / f"{name}.svg").read_text().strip()
    text = re.sub(r'\s(id|class|data-[\w-]+)="[^"]*"', "", text)
    text = re.sub(r">\s+<", "><", text)
    text = re.sub(r"\s+/>", "/>", text)
    return HEX.sub(mute, text)


def folder_names(table: dict[str, str]) -> dict[str, str]:
    """Drops names the UI finds through `short`, and non-ASCII ones."""
    return {
        k: v
        for k, v in table.items()
        if k.isascii() and (short(k) == k or table.get(short(k)) != v)
    }


def short(name: str) -> str:
    """The key the UI also tries: `_api`, `__api__` and `.api` all become `api`."""
    return name.strip("._") or name


def main() -> None:
    package = Path(sys.argv[1])
    manifest = json.loads((package / "dist/material-icons.json").read_text())
    icons = package / "icons"
    folders = [n for n in FOLDER_ICONS if (icons / f"{n}.svg").exists()]
    files = [n for n in FILE_ICONS if (icons / f"{n}.svg").exists()]
    missing = sorted(set(FILE_ICONS + FOLDER_ICONS) - set(files + folders))
    if missing:
        sys.exit(f"not in this version of the theme: {', '.join(missing)}")
    names = set(files) | set(folders) | {f"{n}-open" for n in folders}
    light = {n: f"{n}_light" for n in names if (icons / f"{n}_light.svg").exists()}

    def pick(table: dict[str, str]) -> dict[str, str]:
        return {k: v for k, v in sorted(table.items()) if v in names}

    out = {
        "svg": {n: svg(icons, n) for n in sorted(names)},
        "light": {n: svg(icons, light[n]) for n in sorted(light)},
        "extensions": pick(manifest["fileExtensions"]),
        "fileNames": pick(manifest["fileNames"]),
        "folderNames": folder_names(pick(manifest["folderNames"])),
    }
    version = json.loads((package / "package.json").read_text())["version"]
    target = Path(__file__).resolve().parent.parent / "ui/src/tree/icons/data.ts"
    target.write_text(
        "// Generated by scripts/file_icons.py from Material Icon Theme "
        f"{version} (MIT, see NOTICE). Do not edit.\n"
        "type Table = Record<string, string>;\n"
        "type Icons = { svg: Table; light: Table; extensions: Table; fileNames: Table; folderNames: Table };\n"
        f"const icons: Icons = {json.dumps(out, separators=(',', ':'), ensure_ascii=True)};\n"
        "export default icons;\n"
    )
    print(f"{target}: {len(names)} icons, {target.stat().st_size} bytes")


if __name__ == "__main__":
    main()
