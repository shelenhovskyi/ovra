#!/usr/bin/env python3
"""Generates ui/src/tree/icons/data.ts from Material Icon Theme (MIT).

Usage: python3 scripts/file_icons.py <unpacked material-icon-theme package>

Get the package with `npm pack material-icon-theme@<version>` and untar it.
Only the icons named below are kept, so the bundle stays small; every file
name, extension and folder name the theme maps to one of them comes along.
Colours are muted (less saturation) to fit the Quiet style.
"""

import colorsys
import json
import re
import sys
from pathlib import Path

